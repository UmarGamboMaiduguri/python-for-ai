print("--- For Loop ---")

for number in range(1, 6):
    print("Number:", number)


print("\n--- While Loop ---")

count = 1

while count <= 5:
    print("Count:", count)
    count += 1


print("\n--- Student Scores ---")

scores = [85, 72, 65, 90, 78]

for score in scores:
    print("Score:", score)
